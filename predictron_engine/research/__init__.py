"""Autonomous Research Intelligence — Research Planner, Source Discovery, Collection, and Execution.

The deterministic planning, selection, collection, validation, and
execution layer that, for a given company:

* Decides what information is missing (Research Planner, Sprint 1),
* Decides what research to perform (Research Planner, Sprint 1),
* Orders that research (Research Planner, Sprint 1),
* Selects the highest-quality candidate sources (Source Discovery,
  Sprint 2),
* Executes the research by orchestrating placeholder collectors and
  aggregating deterministic evidence (Evidence Collection, Sprint 3),
* Validates whether collected evidence is trustworthy before downstream
  systems consume it (Evidence Validation, Sprint 4),
* Runs the whole pipeline end to end and reports on it (Research
  Execution, Sprint 5).

The package is **pure planning, collection, validation, and execution**:
no network scraping, no search APIs, no browser automation, no LLMs, and
no live evidence.  Every layer is deterministic — the same input always
produces the same plan, the same ranked source recommendations, the same
collection result, the same validation summary, and the same execution
report.
"""

